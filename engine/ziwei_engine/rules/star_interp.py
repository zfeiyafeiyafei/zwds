def _find_star(chart: NatalChart, name: str) -> tuple[Star, Palace] | None:
    """在命盘上定位星曜：返回（星曜, 所在宫），不在盘上则 None。"""
    for p in chart.palaces:
        for s in (*p.major_stars, *p.minor_stars, *p.adjective_stars):
            if s.name == name:
                return s, p
    return None


def _palace_label(name: str) -> str:
    """宫名统一带「宫」字后缀（"命宫"已自带，"兄弟"等需补）。"""
    return name if name.endswith("宫") else name + "宫"


def _palace_majors(chart: NatalChart, palace: Palace) -> tuple[list[Star], Palace]:
    """宫位主星及其来源宫：空宫（无正曜）借对宫主星论之。"""
    if palace.major_stars:
        return list(palace.major_stars), palace
    opposite = chart.palaces[(palace.index + 6) % 12]
    return list(opposite.major_stars), opposite


def _role_brightness_note(s: Star) -> str:
    """命身四星断语中的亮度注记（风险文本已在角色断语内，此处不重复）。"""
