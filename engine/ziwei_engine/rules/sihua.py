"""生年四化：十天干 → 化禄/化权/化科/化忌。

三合派传统表（对齐 iztro 默认配置）：
甲 廉破武阳 | 乙 机梁紫阴 | 丙 同机昌廉 | 丁 阴同机巨 | 戊 贪阴右机
己 武贪梁曲 | 庚 阳武阴同 | 辛 巨阳曲昌 | 壬 梁紫左武 | 癸 破巨阴贪
"""

# SIHUA[年干索引] = (化禄星, 化权星, 化科星, 化忌星)
SIHUA: list[tuple[str, str, str, str]] = [
    ("廉贞", "破军", "武曲", "太阳"),  # 甲
    ("天机", "天梁", "紫微", "太阴"),  # 乙
    ("天同", "天机", "文昌", "廉贞"),  # 丙
    ("太阴", "天同", "天机", "巨门"),  # 丁
    ("贪狼", "太阴", "右弼", "天机"),  # 戊
    ("武曲", "贪狼", "天梁", "文曲"),  # 己
    ("太阳", "武曲", "太阴", "天同"),  # 庚
    ("巨门", "太阳", "文曲", "文昌"),  # 辛
    ("天梁", "紫微", "左辅", "武曲"),  # 壬
    ("破军", "巨门", "太阴", "贪狼"),  # 癸
]

HUA_NAMES: tuple[str, str, str, str] = ("禄", "权", "科", "忌")


def birth_mutagens(year_gan: int) -> dict[str, str]:
    """返回 {星名: 四化类型}，如 {'廉贞': '禄', ...}。"""
    return {star: hua for star, hua in zip(SIHUA[year_gan], HUA_NAMES)}
